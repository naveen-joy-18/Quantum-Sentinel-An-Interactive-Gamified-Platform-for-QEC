"""Serialize the actual generated Qiskit circuit, its check wires and readouts.

Every rendered gate comes from QuantumCircuit.data, not a mock board. Check
operations are conservatively classified as gates touching actual ancilla wires;
this is not a claim that their abstract spacetime support has been localized to
only these instructions.
"""
from __future__ import annotations


def _indices(qc, bits):
    out=[]
    for bit in bits:
        if isinstance(bit, int):
            out.append(bit)
            continue
        try:
            out.append(qc.find_bit(bit).index)
        except Exception:
            out.append(int(bit))
    return out


def serialize_circuit(qc, checked=None, n_data=0):
    ancillas = sorted(set(_indices(qc, getattr(checked, 'check_qubits', [])))) if checked else []
    # Additional physical qubits are treated as ancilla even when a paulice
    # version does not expose `check_qubits` as stable public metadata.
    if checked:
        ancillas = sorted(set(ancillas) | set(range(n_data, qc.num_qubits)))
    operations=[]
    syndrome_readouts=[]
    for i, entry in enumerate(qc.data):
        params=[]
        for value in entry.operation.params:
            try:
                params.append(float(value))
            except (ValueError, TypeError):
                params.append(str(value))
        qubits = _indices(qc, entry.qubits)
        clbits = _indices(qc, entry.clbits)
        touches_ancilla=any(q in ancillas for q in qubits)
        kind = ('syndrome_measurement' if entry.operation.name=='measure' and touches_ancilla
                else 'payload_measurement' if entry.operation.name=='measure'
                else 'check_related' if touches_ancilla else 'payload')
        op={'index':i,'name':entry.operation.name,'qubits':qubits,
            'clbits':clbits,'params':params,'role':kind}
        operations.append(op)
        if kind=='syndrome_measurement':
            syndrome_readouts.append({'operation_index':i,'ancilla':qubits[0],
                                       'classical_bit':clbits[0] if clbits else None})
    supports=[]
    for item in getattr(checked,'check_support',[]) if checked else []:
        try:
            supports.append([str(part) for part in item])
        except TypeError:
            supports.append([str(item)])
    return {'n_qubits':qc.num_qubits,'n_clbits':qc.num_clbits,
            'data_qubits':n_data,'depth':qc.depth(), 'operations':operations,
            'ancilla_indices':ancillas,'check_support':supports,
            'syndrome_readouts':syndrome_readouts,'actual_circuit':True,
            'note':('Exact circuit program order; colored check-related gates touch physical ancillas. '
                    'Syndrome histograms/shot rejection come from execution, not this static circuit.')}


def generate_circuit(n, depth, seed, t_count, target_order, checks, p2, readout, hand=False):
    from src.experiment import payload, measure_payload, noise_models
    from qiskit_paulice import add_pauli_checks
    un = payload(n, depth, t_count, seed)
    if t_count and checks:
        if not hand:
            raise ValueError('Automatic qiskit-paulice checks cannot be inserted across a T-doped payload; '
                             'hand=True inserts a hand-made I/Z-aligned parity check instead.')
        if len(target_order) < checks or len(set(target_order)) != len(target_order):
            raise ValueError('A check needs a unique target qubit')
        targets = list(target_order[:checks])
        from src.checks import add_hand_check
        prot_un, ancilla = add_hand_check(un, targets)
        qc = measure_payload(prot_un, prot_un.num_qubits)
        return serialize_circuit(qc, checked=_HandMeta(ancilla, targets), n_data=n)
    qc = measure_payload(un, n)
    if checks == 0:
        return serialize_circuit(qc, n_data=n)
    if len(target_order) < checks or len(set(target_order)) != len(target_order):
        raise ValueError('A check needs a unique ordered target qubit')
    chooser, _ = noise_models(p2, readout)
    checked_versions = add_pauli_checks(qc, list(target_order), chooser,
                                        cost='gamma', method='windowed', seed=seed)
    if checks >= len(checked_versions):
        raise ValueError('Requested number of checks was not generated by qiskit-paulice')
    chosen = checked_versions[checks]
    return serialize_circuit(chosen.circuit, checked=chosen, n_data=n)


class _HandMeta:
    """Minimal checked-compatible metadata for a hand-made parity check."""

    def __init__(self, ancilla, targets):
        self.check_qubits = [ancilla]
        self.check_support = [[f'Z on q{int(t)}'] for t in targets]
